import SwiftUI

extension Font {
    static func alika(size: CGFloat = 14) -> Font {
        return .custom("Alika Misely", size: size)
    }
    
    static func bolina(size: CGFloat = 14) -> Font {
        return .custom("Bolina", size: size)
    }
}

